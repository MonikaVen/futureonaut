interface LangState {
  lang: LangCode;
  setLang: (code: LangCode) => void;
  t: (key: string) => string;
}

const LangContext = createContext<LangState | null>(null);

function normalizeNavLang(code: string): LangCode | null {
  const base = code.slice(0, 2).toLowerCase();
  if (base === "nb" || base === "nn") return "no";
  if (UI_LANGS.some((l) => l.code === base)) return base as LangCode;
  return null;
}

function readInitial(): LangCode {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved) {
    const normalized = normalizeNavLang(saved);
    if (normalized) return normalized;
  }
  const nav = normalizeNavLang(navigator.language || "en");
  return nav || "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(readInitial);

  const setLang = (code: LangCode) => {
    localStorage.setItem(STORAGE_KEY, code);
    setLangState(code);
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang,
      t: (key: string) => COPY[lang][key] || COPY.en[key] || key,
    }),
    [lang]
  );

  return createElement(LangContext.Provider, { value }, children);
}

export function useLanguage() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLanguage outside provider");
  return ctx;
}

export function LanguageSelect({ className = "" }: { className?: string }) {
  const { lang, setLang, t } = useLanguage();

  return (
    <label className={`lang-select${className ? ` ${className}` : ""}`}>
      <span className="lang-select-label">{t("language")}</span>
      <select
        value={lang}
        onChange={(e) => setLang(e.target.value as LangCode)}
        aria-label={t("language")}
      >
        {UI_LANGS.map((item) => (
          <option key={item.code} value={item.code}>
            {item.label}
          </option>
        ))}
      </select>
    </label>
  );
}
